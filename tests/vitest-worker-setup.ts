import http from "http";
import https from "https";
import net from "net";

// Dedicated non-pooling agent for local loopback test traffic (no proxy symbols)
const directHttpAgent = new http.Agent({ keepAlive: false });
const directHttpsAgent = new https.Agent({ keepAlive: false });
for (const agent of [directHttpAgent, directHttpsAgent]) {
  for (const sym of Object.getOwnPropertySymbols(agent)) {
    if (sym.toString().toLowerCase().includes("proxy")) {
      delete (agent as any)[sym];
    }
  }
}

const isLoopback = (opts: any) => {
  if (!opts) return true;
  const target = String(opts.hostname || opts.host || "").toLowerCase();
  return (
    !target ||
    target.startsWith("127.0.0.1") ||
    target.startsWith("localhost") ||
    target.startsWith("::1") ||
    target.startsWith("[::1]")
  );
};

const origHttpRequest = http.request;
(http as any).request = function(...args: any[]) {
  let opts: any;
  if (typeof args[0] === "string" || args[0] instanceof URL) {
    if (typeof args[1] === "function" || args[1] === undefined) {
      opts = {};
      args.splice(1, 0, opts);
    } else {
      opts = args[1];
    }
  } else {
    opts = args[0] = args[0] || {};
  }
  opts.agent = directHttpAgent;
  return origHttpRequest.apply(this, args as any);
};

const origHttpsRequest = https.request;
(https as any).request = function(...args: any[]) {
  let opts: any;
  if (typeof args[0] === "string" || args[0] instanceof URL) {
    if (typeof args[1] === "function" || args[1] === undefined) {
      opts = {};
      args.splice(1, 0, opts);
    } else {
      opts = args[1];
    }
  } else {
    opts = args[0] = args[0] || {};
  }
  opts.agent = directHttpsAgent;
  return origHttpsRequest.apply(this, args as any);
};

const OrigClientRequest = http.ClientRequest;
(http as any).ClientRequest = function(input: any, options: any, cb: any) {
  if (typeof options === "function") {
    cb = options;
    options = {};
  } else {
    options = options || {};
  }
  options.agent = directHttpAgent;
  return new OrigClientRequest(input, options, cb);
};

http.globalAgent = directHttpAgent;
https.globalAgent = directHttpsAgent;

import { inject, beforeAll } from 'vitest';
import { setupTestSchema, truncateTestSchema } from '../src/db/migrateTestSchema';

// Get the runId generated by globalSetup
const runId = inject('runId') || 'standalone';
const poolId = process.env.VITEST_POOL_ID || '1';

// Set the schema name BEFORE any other imports are evaluated
const schemaName = `lifeloop_test_${runId}_w${poolId}`;
process.env.TEST_SCHEMA = schemaName;
console.log(`[Worker Pool ID: ${poolId}] Initializing worker with schema ${schemaName}`);

// Record exact schema name in run tracker for exact teardown
import fs from 'fs';
import path from 'path';
const trackerFile = path.join(process.cwd(), `.run_schemas_${runId}.json`);
let schemas: string[] = [];
try {
  if (fs.existsSync(trackerFile)) {
    schemas = JSON.parse(fs.readFileSync(trackerFile, 'utf8'));
  }
} catch {}
if (!schemas.includes(schemaName)) {
  schemas.push(schemaName);
  fs.writeFileSync(trackerFile, JSON.stringify(schemas), 'utf8');
}

// Execute schema setup directly, blocking test execution until ready
await setupTestSchema(schemaName);

// Truncate all tables before the test file runs to ensure clean worker state
await truncateTestSchema(schemaName);

beforeAll(async () => {
  await truncateTestSchema(schemaName);
});
